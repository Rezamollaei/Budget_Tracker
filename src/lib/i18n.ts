const MESSAGES: Record<Lang, Record<MessageKey, string>> = { en, it }

export type Vars = Record<string, string | number>

export function translate(lang: Lang, key: MessageKey, vars?: Vars): string {
  const template = MESSAGES[lang][key] ?? en[key]
  return vars ? template.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : template
}

type PluralBase<K> = K extends `${infer B}_one` ? B : never
export type PluralKey = PluralBase<MessageKey>

export function translatePlural(lang: Lang, key: PluralKey, n: number, vars?: Vars): string {
  return translate(lang, `${key}_${n === 1 ? 'one' : 'other'}` as MessageKey, { n, ...vars })
}

export function localeFor(lang: Lang): string {
  return LANGS.find((l) => l.id === lang)?.locale ?? 'en'
}

export function detectLang(): Lang {
  try {
    return navigator.language?.toLowerCase().startsWith('it') ? 'it' : 'en'
  } catch {
    return 'en'
  }
}
